import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { GoogleGenAI } from '@google/genai';

const main = async () => {
  console.info('Running Continuous Improvement Loop...');

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    console.warn('GEMINI_API_KEY is not set. Skipping real AI improvement generation.');
    return;
  }

  console.info('Gathering repository context...');

  let gitLog = '';
  try {
    gitLog = execFileSync('git', ['log', '-n', '50', '--oneline']).toString();
  } catch (e) {
    console.warn('Could not fetch git history.');
  }

  let metadataStr = '';
  const metadataPath = path.resolve(process.cwd(), 'metadata.json');
  if (fs.existsSync(metadataPath)) {
    metadataStr = fs.readFileSync(metadataPath, 'utf8');
  }

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `
You are an expert AI software architect running a continuous improvement loop on a repository.
Analyze the following context about the repository.

Repository Metadata:
${metadataStr.substring(0, 5000)}

Recent Git History:
${gitLog.substring(0, 2000)}

Tasks:
1. Identify potential technical debt based on the structure and history.
2. Identify documentation gaps (e.g., missing SDK docs, API docs).
3. Identify architectural concerns or areas for optimization.
4. Suggest concrete, actionable recommendations for improvement.
5. Provide a summary of the repository's overall health and trajectory.

Generate a comprehensive markdown report.
`;

  let responseText = '';
  try {
    console.info('Generating improvement recommendations...');
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });
    responseText = response.text || 'No response generated by AI.';
  } catch (error) {
    console.error('AI Generation failed:', error);
    responseText = 'AI Generation failed due to an API error.';
  }

  const outDir = path.resolve(process.cwd(), 'docs/improvements');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const reportContent = `# Continuous Improvement Report\nDate: ${new Date().toISOString()}\n\n${responseText}\n`;

  fs.writeFileSync(path.join(outDir, `improvement-${Date.now()}.md`), reportContent);
  fs.writeFileSync(path.resolve(process.cwd(), 'latest-improvement-report.md'), reportContent);

  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, reportContent);
  }

  console.info('Continuous Improvement Report generated successfully.');
};

main().catch(console.error);
