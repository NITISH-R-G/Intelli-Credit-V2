import { GoogleGenAI } from '@google/genai';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as crypto from 'node:crypto';

function getFiles(dir: string, fileList: string[] = []): string[] {
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) {
      if (!['node_modules', '.git', 'dist', 'coverage', '.github'].includes(file)) {
        getFiles(filePath, fileList);
      }
    } else {
      if (filePath.endsWith('.ts') || filePath.endsWith('.tsx')) {
        fileList.push(filePath);
      }
    }
  }
  return fileList;
}

async function generateReport() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    process.stderr.write('GEMINI_API_KEY is not set.\n');
    process.exit(1);
  }

  const allFiles = getFiles('.');
  // Sample core files
  const coreFiles = allFiles.filter(
    (f) => f.includes('src/') || f.includes('api/') || f.includes('scripts/'),
  );

  // Use crypto for safe random
  const sampledFiles = coreFiles
    .sort(() => {
      return crypto.randomBytes(1)[0] / 255 - 0.5;
    })
    .slice(0, 10);

  let codebaseContext = '';
  for (const file of sampledFiles) {
    const content = fs.readFileSync(file, 'utf-8');
    codebaseContext += `\n--- File: ${file} ---\n${content.substring(0, 2000)}\n`;
  }

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `
You are an AI analyzing the Intelli-Credit repository for continuous improvement.
Based on the following sampled source code files, generate a markdown report containing:
1. Detected weaknesses or technical debt
2. Documentation gaps
3. Potential security or performance issues
4. Actionable recommendations for refactoring or fixing

Codebase Context:
${codebaseContext}

Output the report in Markdown format.
`;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    if (response.text) {
      fs.mkdirSync('docs/history', { recursive: true });
      fs.writeFileSync('docs/history/ai-improvement-report.md', response.text, 'utf-8');
      process.stdout.write('AI improvement report generated successfully.\n');
    } else {
      process.stderr.write('No response text generated by AI.\n');
    }
  } catch (error) {
    process.stderr.write(`Failed to generate improvement report: ${String(error)}\n`);
    process.exit(1);
  }
}

await generateReport().catch(() => process.exit(1));
