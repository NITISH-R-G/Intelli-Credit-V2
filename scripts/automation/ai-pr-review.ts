import * as fs from 'node:fs';
import { GoogleGenAI } from '@google/genai';

async function reviewPR() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    process.stderr.write('GEMINI_API_KEY environment variable is missing.\n');
    process.exit(1);
  }

  const diffPath = 'pr-diff.txt';
  if (!fs.existsSync(diffPath)) {
    process.stderr.write('PR diff file pr-diff.txt is missing.\n');
    process.exit(1);
  }

  const diffContent = fs.readFileSync(diffPath, 'utf8');
  if (!diffContent || diffContent.trim() === '') {
    process.stderr.write('PR diff is empty.\n');
    process.exit(0);
  }

  const eventPath = process.env.GITHUB_EVENT_PATH;
  let prTitle = 'Unknown PR';
  let prBody = 'No description provided.';

  if (eventPath && fs.existsSync(eventPath)) {
    const eventData = JSON.parse(fs.readFileSync(eventPath, 'utf8')) as Record<string, unknown>;
    const pr = eventData.pull_request as Record<string, unknown>;
    if (pr) {
      if (pr.title) prTitle = pr.title as string;
      if (pr.body) prBody = pr.body as string;
    }
  }

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `You are a senior staff software engineer acting as the automated AI PR Reviewer for the 'intelli-credit' open-source repository.

Review the following Pull Request.
Title: ${prTitle}
Description: ${prBody}

Here is the Git diff:
\`\`\`diff
${diffContent}
\`\`\`

Analyze the code changes for:
1. Bugs or logic errors.
2. Performance issues.
3. Security vulnerabilities.
4. Adherence to TypeScript strict mode and clean code principles.
5. Best practices.

Provide a comprehensive, constructive, and highly technical review.
If the code looks good, state that clearly.
If there are issues, provide actionable feedback and code snippets for fixes.
Format your review in Markdown.`;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    const aiResponse = response.text;
    if (aiResponse) {
      fs.writeFileSync('pr-comment.txt', aiResponse, 'utf8');
      process.stdout.write('PR review generated successfully.\n');
    } else {
      process.stderr.write('No response generated by Gemini.\n');
      process.exit(1);
    }
  } catch (error) {
    process.stderr.write(
      `Failed to generate PR review: ${error instanceof Error ? error.message : 'Unknown error'}\n`,
    );
    process.exit(1);
  }
}

await reviewPR().catch((err) => {
  process.stderr.write(
    `Unexpected error: ${err instanceof Error ? err.message : 'Unknown error'}\n`,
  );
  process.exit(1);
});
