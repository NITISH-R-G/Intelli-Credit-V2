import * as fs from 'node:fs';
import { GoogleGenAI } from '@google/genai';
import { execFileSync } from 'node:child_process';

async function review(): Promise<void> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    console.warn('GEMINI_API_KEY is not set. Exiting ai-pr-review without error.');
    process.exit(0);
  }

  const prUrl = process.env.PR_URL;
  if (!prUrl) {
    console.error('PR_URL environment variable is missing.');
    process.exit(1);
  }

  const githubToken = process.env.GITHUB_TOKEN;
  if (!githubToken) {
    console.error('GITHUB_TOKEN environment variable is missing.');
    process.exit(1);
  }

  try {
    // Fetch PR diff using curl securely via execFileSync
    execFileSync('curl', [
      '-s',
      '-H',
      `Authorization: Bearer ${githubToken}`,
      '-H',
      'Accept: application/vnd.github.v3.diff',
      prUrl,
      '-o',
      'pr-diff.txt',
    ]);

    if (!fs.existsSync('pr-diff.txt')) {
      console.error('Failed to download PR diff.');
      process.exit(1);
    }

    const diffText = fs.readFileSync('pr-diff.txt', 'utf-8');
    if (!diffText || diffText.trim().length === 0) {
      console.info('PR diff is empty. Nothing to review.');
      process.exit(0);
    }

    const ai = new GoogleGenAI({ apiKey });

    const prompt = `
    You are an expert AI maintainer for the Intelli-Credit Terminal open-source repository.
    Review the following pull request diff.
    Look for bugs, security vulnerabilities, performance issues, lack of strict typing,
    violation of formatting rules, and deviations from architectural principles.

    Diff:
    ${diffText}

    Please provide a professional, constructive code review. Point out any specific lines with issues and suggest improvements.
    Output only the Markdown content of your review.
    `;

    const response = await ai.models.generateContent({
      model: 'gemini-2.0-flash',
      contents: prompt,
    });

    if (response.text) {
      fs.writeFileSync('pr-comment.txt', response.text);
      console.info('PR review comment generated successfully.');
    } else {
      console.warn('No response text generated by Gemini.');
    }
  } catch (err) {
    console.error('Error during AI PR review:', err);
    process.exit(1);
  }
}

void review();
