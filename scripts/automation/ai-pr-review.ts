import fs from 'node:fs';
import path from 'node:path';
import { GoogleGenAI } from '@google/genai';

function getFiles(dirPath: string): string[] {
  const files: string[] = [];
  try {
    const items = fs.readdirSync(dirPath, { withFileTypes: true });
    for (const item of items) {
      if (item.name === 'node_modules' || item.name === 'dist' || item.name === '.git') continue;
      const fullPath = path.join(dirPath, item.name);
      if (item.isDirectory()) {
        files.push(...getFiles(fullPath));
      } else if (fullPath.endsWith('.ts') || fullPath.endsWith('.tsx')) {
        files.push(fullPath);
      }
    }
  } catch (err) {
    console.warn(`Could not read directory: ${dirPath}`, err);
  }
  return files;
}

async function reviewPR() {
  if (!process.env.GEMINI_API_KEY) {
    console.warn('GEMINI_API_KEY not found. Skipping PR review.');
    process.exit(0);
  }

  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath) {
    console.error('GITHUB_EVENT_PATH is not defined.');
    process.exit(1);
  }

  try {
    const fileContent = fs.readFileSync(eventPath, 'utf8');
    const eventData = JSON.parse(fileContent) as {
      pull_request?: { title: string; body?: string };
    };
    const pr = eventData.pull_request;
    if (!pr) {
      console.info('No pull_request data found in event payload.');
      process.exit(0);
    }

    let diffText = '';
    try {
      diffText = fs.readFileSync('pr-diff.txt', 'utf8');
    } catch (err) {
      console.warn('pr-diff.txt not found. Cannot review diff.', err);
      process.exit(0);
    }

    const title = pr.title;
    const body = pr.body || 'No description provided.';

    // Gather some context (only first few files to not blow up context)
    let repoContext = '';
    const srcFiles = getFiles('src').slice(0, 5);
    for (const file of srcFiles) {
      try {
        repoContext += `\n--- ${file} ---\n${fs.readFileSync(file, 'utf8').substring(0, 500)}`;
      } catch (err) {
        console.warn(`Could not read file for context: ${file}`, err);
      }
    }

    const prompt = `You are a senior staff engineer performing an automated PR review.
Review the following Pull Request for quality, security, performance, and best practices.

Pull Request Title: ${title}
Pull Request Body: ${body}

PR Diff:
${diffText}

A tiny snippet of Repo Context:
${repoContext}

Provide a concise, constructive, and actionable review. Do not just summarize the changes. Point out potential bugs, security issues, or suggest refactors. Use Markdown format.`;

    const response = await ai.models.generateContent({
      model: 'gemini-2.0-flash',
      contents: prompt,
    });

    const aiComment = response.text;
    if (aiComment) {
      fs.writeFileSync('pr-comment.txt', aiComment, 'utf8');
      console.info('Generated PR review successfully.');
    } else {
      console.error('No text generated by Gemini API.');
    }
  } catch (err) {
    console.error('Error during AI PR review:', err);
    process.exit(1);
  }
}

void reviewPR();
