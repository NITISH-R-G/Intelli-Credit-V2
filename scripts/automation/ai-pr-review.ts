import { GoogleGenAI } from '@google/genai';
import * as fs from 'node:fs';

async function reviewPr() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    process.stderr.write('GEMINI_API_KEY is not set.\n');
    process.exit(1);
  }

  const diffPath = 'pr-diff.txt';
  if (!fs.existsSync(diffPath)) {
    process.stderr.write(`Diff file not found at ${diffPath}.\n`);
    process.exit(0);
  }

  const diffContent = fs.readFileSync(diffPath, 'utf-8');
  if (!diffContent.trim()) {
    process.stdout.write('Diff is empty. Nothing to review.\n');
    process.exit(0);
  }

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `
You are an AI senior staff engineer reviewing a Pull Request on the Intelli-Credit repository.
Analyze the following diff and provide a constructive, helpful code review.
Focus on:
1. Potential bugs or regressions
2. Code quality and maintainability
3. Security concerns
4. Adherence to best practices (e.g., no console.log, strict typing)

Diff:
${diffContent.substring(0, 50000)} // truncate to prevent context limits
`;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    if (response.text) {
      fs.writeFileSync('pr-comment.txt', response.text, 'utf-8');
      process.stdout.write('PR review comment generated successfully.\n');
    } else {
      process.stderr.write('No response text generated by AI.\n');
    }
  } catch (error) {
    process.stderr.write(`Failed to generate PR review: ${String(error)}\n`);
    process.exit(1);
  }
}

await reviewPr().catch(() => process.exit(1));
