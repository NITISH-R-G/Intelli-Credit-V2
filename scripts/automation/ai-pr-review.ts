import { GoogleGenAI } from '@google/genai';
import * as fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const apiKey = process.env.GEMINI_API_KEY;

if (!apiKey) {
  console.info('Skipping AI PR review: GEMINI_API_KEY is not set.');
  process.exit(0);
}

const ai = new GoogleGenAI({ apiKey });

async function reviewPR() {
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath) {
    console.error('GITHUB_EVENT_PATH not set.');
    process.exit(1);
  }

  const eventData = JSON.parse(fs.readFileSync(eventPath, 'utf8'));
  const pr = eventData.pull_request;

  if (!pr) {
    console.error('No pull request data found in event payload.');
    process.exit(1);
  }

  const prUrl = pr.url;
  const githubToken = process.env.GITHUB_TOKEN;

  if (!githubToken) {
    console.error('GITHUB_TOKEN is not set.');
    process.exit(1);
  }

  let diff = '';
  try {
    const diffBuffer = execFileSync('curl', [
      '-s',
      '-H',
      `Authorization: Bearer ${githubToken}`,
      '-H',
      'Accept: application/vnd.github.v3.diff',
      prUrl,
    ]);
    diff = diffBuffer.toString();
    fs.writeFileSync('pr-diff.txt', diff, 'utf8');
  } catch (error) {
    console.error('Error fetching PR diff:', error);
    process.exit(1);
  }

  const diffContent = fs.readFileSync('pr-diff.txt', 'utf8');

  if (!diffContent) {
    console.info('Empty diff found.');
    process.exit(0);
  }

  const prompt = `
You are an expert AI code reviewer. Please review the following pull request diff. Provide a constructive review, pointing out potential bugs, security issues, performance problems, and style inconsistencies. Suggest improvements.

Diff:
${diffContent}
`;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.0-flash',
      contents: prompt,
    });

    const comment = response.text || 'LGTM! (Generated by AI)';
    fs.writeFileSync('pr-comment.txt', comment, 'utf8');
    console.info('PR review comment generated successfully.');
  } catch (error) {
    console.error('Error generating PR review comment:', error);
    process.exit(1);
  }
}

void reviewPR();
