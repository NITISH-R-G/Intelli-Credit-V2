import { GoogleGenAI } from '@google/genai';
import * as fs from 'fs';
import * as path from 'path';

async function prReview() {
  if (!process.env.GEMINI_API_KEY) {
    console.warn('GEMINI_API_KEY not found. Skipping AI PR review.');
    process.exit(0);
  }

  const diffPath = path.join(process.cwd(), 'pr-diff.txt');
  if (!fs.existsSync(diffPath)) {
    console.error('pr-diff.txt not found. Please ensure the CI workflow creates this file.');
    process.exit(1);
  }

  const diff = fs.readFileSync(diffPath, 'utf8');
  if (!diff || diff.trim().length === 0) {
    console.info('No changes in PR diff. Skipping review.');
    const outPath = path.join(process.cwd(), 'pr-review-comment.txt');
    fs.writeFileSync(outPath, 'No significant changes detected to review.');
    process.exit(0);
  }

  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
  const prompt = `
You are an expert AI PR Reviewer for the Intelli-Credit repository (React/Express/Vite/TypeScript).
Please review the following git diff and provide constructive feedback.
Focus on:
- Potential bugs or edge cases
- Code readability and maintainability
- Security vulnerabilities
- Adherence to modern React and TypeScript best practices (e.g. types, avoiding \`any\`, component structure)
Keep your feedback concise and friendly. Format as Markdown.

GIT DIFF:
\`\`\`diff
${diff.substring(0, 15000)} // Truncating to avoid massive prompts just in case
\`\`\`
  `.trim();

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.0-flash',
      contents: prompt,
    });

    const text = response.text || "LGTM! (Generated by AI fallback)";

    const outPath = path.join(process.cwd(), 'pr-review-comment.txt');
    fs.writeFileSync(outPath, text);
    console.info('PR review comment generated successfully.');
  } catch (error) {
    console.error('Error generating PR review:', error);
    process.exit(1);
  }
}

void prReview();
