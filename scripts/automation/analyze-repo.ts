import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

function analyzeRepo() {
  console.info('Analyzing repository...');

  let fileCount = 0;
  let tsCount = 0;
  let tsxCount = 0;

  function walkDir(dir: string) {
    const files = readdirSync(dir);
    for (const file of files) {
      if (file === 'node_modules' || file === '.git' || file === 'dist') continue;

      const fullPath = join(dir, file);
      const stat = statSync(fullPath);

      if (stat.isDirectory()) {
        walkDir(fullPath);
      } else {
        fileCount++;
        if (file.endsWith('.ts')) tsCount++;
        if (file.endsWith('.tsx')) tsxCount++;
      }
    }
  }

  walkDir('.');

  let depsCount = 0;
  let devDepsCount = 0;
  try {
    const packageJson = JSON.parse(readFileSync('package.json', 'utf-8'));
    depsCount = Object.keys(packageJson.dependencies || {}).length;
    devDepsCount = Object.keys(packageJson.devDependencies || {}).length;
  } catch (error) {
    console.error('Failed to parse package.json:', error);
  }

  const report = `# Repository Analysis

This report is auto-generated by \`npm run analyze:repo\`.

## File Statistics
- **Total Files**: ${fileCount}
- **TypeScript Files (.ts)**: ${tsCount}
- **TSX Files (.tsx)**: ${tsxCount}

## Dependencies
- **Dependencies**: ${depsCount}
- **Dev Dependencies**: ${devDepsCount}
`;

  writeFileSync('docs/repo-analysis.md', report);
  console.info('Repository analysis saved to docs/repo-analysis.md');
}

analyzeRepo();
