import { GoogleGenAI } from '@google/genai';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { execFileSync } from 'node:child_process';

function getFiles(dir: string, fileList: string[] = []): string[] {
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) {
      if (!['node_modules', '.git', 'dist', 'coverage', '.github'].includes(file)) {
        getFiles(filePath, fileList);
      }
    } else {
      if (filePath.endsWith('.ts') || filePath.endsWith('.tsx')) {
        fileList.push(filePath);
      }
    }
  }
  return fileList;
}

async function analyzeRepo() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    process.stderr.write('GEMINI_API_KEY is not set.\n');
    process.exit(1);
  }

  // Ensure architecture directory exists
  fs.mkdirSync('docs/architecture', { recursive: true });

  // Generate dependency graph with madge
  try {
    process.stdout.write('Generating dependency graph with madge...\n');
    execFileSync(
      'npx',
      [
        'madge',
        '--image',
        'docs/architecture/dependency-graph.svg',
        '--extensions',
        'ts,tsx',
        'src',
        'api',
        'scripts',
      ],
      { stdio: 'inherit' },
    );
  } catch (error) {
    process.stderr.write(`Failed to generate dependency graph: ${String(error)}\n`);
    // Non-fatal if madge fails (e.g. no graphviz)
  }

  const allFiles = getFiles('.');
  const coreFiles = allFiles.filter(
    (f) => f.includes('src/') || f.includes('api/') || f.includes('scripts/'),
  );

  let codebaseContext = '';
  // Avoid large files
  for (const file of coreFiles.slice(0, 50)) {
    try {
      const content = fs.readFileSync(file, 'utf-8');
      codebaseContext += `\n--- File: ${file} ---\n${content.substring(0, 1000)}\n`;
    } catch {
      // ignore read error
    }
  }

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `
You are an AI tasked with generating a knowledge graph for the Intelli-Credit repository.
Analyze the following source files and output a JSON representation of a knowledge graph.
The JSON should have a top-level key "nodes" and "edges".
Nodes should represent files, modules, functions, or services.
Edges should represent dependencies or relationships.

Codebase Context:
${codebaseContext}

Output ONLY valid JSON.
`;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    if (response.text) {
      let jsonContent = response.text;
      // Strip markdown code blocks if any
      jsonContent = jsonContent
        .replace(/^```json/m, '')
        .replace(/^```/m, '')
        .trim();
      fs.writeFileSync('docs/architecture/knowledge-graph.json', jsonContent, 'utf-8');
      process.stdout.write('Knowledge graph generated successfully.\n');
    } else {
      process.stderr.write('No response text generated by AI.\n');
    }
  } catch (error) {
    process.stderr.write(`Failed to generate knowledge graph: ${String(error)}\n`);
    process.exit(1);
  }
}

await analyzeRepo().catch(() => process.exit(1));
