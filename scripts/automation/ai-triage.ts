import fs from 'node:fs';
import { GoogleGenAI } from '@google/genai';

async function triage() {
  if (!process.env.GEMINI_API_KEY) {
    console.warn('GEMINI_API_KEY not found. Skipping AI Triage.');
    process.exit(0);
  }

  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath) {
    console.error('GITHUB_EVENT_PATH is not defined.');
    process.exit(1);
  }

  try {
    const eventData = JSON.parse(fs.readFileSync(eventPath, 'utf8'));
    const issue = eventData.issue;
    if (!issue) {
      console.info('No issue data found in event payload.');
      process.exit(0);
    }

    const title = issue.title;
    const body = issue.body || 'No description provided.';
    const author = issue.user.login;

    const prompt = `You are an AI Maintainer for this open-source repository.
Please review the following issue and provide a polite, helpful response for the author.
Acknowledge the issue, suggest some initial troubleshooting steps, and let them know the maintainers will review it shortly.

Issue Title: ${title}
Issue Body: ${body}
Author: ${author}

Keep the response helpful, constructive, and concise.`;

    const response = await ai.models.generateContent({
      model: 'gemini-2.0-flash',
      contents: prompt,
    });

    const aiComment = response.text;
    if (aiComment) {
      fs.writeFileSync('triage-comment.txt', aiComment, 'utf8');
      console.info('Generated triage comment successfully.');
    } else {
      console.error('No text generated by Gemini API.');
    }
  } catch (err) {
    console.error('Error during AI triage:', err);
    process.exit(1);
  }
}

void triage();
