import { GoogleGenAI } from '@google/genai';
import * as fs from 'node:fs';

async function triage() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    process.stderr.write('GEMINI_API_KEY is not set.\n');
    process.exit(1);
  }

  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath) {
    process.stderr.write('GITHUB_EVENT_PATH is not set.\n');
    process.exit(1);
  }

  const event = JSON.parse(fs.readFileSync(eventPath, 'utf-8')) as Record<string, unknown>;
  const issue = event.issue as Record<string, unknown> | undefined;

  if (!issue) {
    process.stderr.write('No issue found in event payload.\n');
    process.exit(0);
  }

  const ai = new GoogleGenAI({ apiKey });

  const prompt = `
You are an AI senior staff engineer triaging a new issue on the Intelli-Credit repository.
Analyze the following issue and provide a friendly, helpful, and technically accurate initial response.
If the issue is a bug, suggest potential areas to investigate. If it's a feature request, provide thoughts on feasibility and architecture.

Issue Title: ${String(issue.title)}
Issue Body:
${String(issue.body)}
`;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    if (response.text) {
      fs.writeFileSync('triage-comment.txt', response.text, 'utf-8');
      process.stdout.write('Triage comment generated successfully.\n');
    } else {
      process.stderr.write('No response text generated by AI.\n');
    }
  } catch (error) {
    process.stderr.write(`Failed to generate triage comment: ${String(error)}\n`);
    process.exit(1);
  }
}

await triage().catch(() => process.exit(1));
